import { mkdir, writeFile } from 'node:fs/promises'
import { URL } from 'node:url'

/* global console, fetch */

import { kanaCatalog } from '../src/data/kana/kanaCatalog.js'

const KANJIVG_COMMIT = '70a0b7ae0c18ceb5cb358274b029cce0234a43bc'
const SOURCE_BASE = `https://raw.githubusercontent.com/KanjiVG/kanjivg/${KANJIVG_COMMIT}/kanji`
const OUTPUT_FILE = new URL('../src/data/writing/kanaStrokes.js', import.meta.url)

function codepointFile(character) {
  return `${character.codePointAt(0).toString(16).padStart(5, '0')}.svg`
}

function extractStrokes(svg) {
  return [...svg.matchAll(/<path[^>]+d="([^"]+)"\s*\/>/g)].map((match) => match[1])
}

function extractNumbers(svg) {
  return [...svg.matchAll(/<text transform="matrix\(1 0 0 1 ([\d.-]+) ([\d.-]+)\)">(\d+)<\/text>/g)]
    .map((match) => ({ x: Number(match[1]), y: Number(match[2]), value: Number(match[3]) }))
}

function round(value) {
  return Math.round(value * 100) / 100
}

function sampleStroke(path, samplesPerCurve = 4) {
  const values = (path.match(/-?\d*\.?\d+/g) ?? []).map(Number)
  if (values.length < 2 || (values.length - 2) % 6 !== 0) {
    throw new Error(`Unsupported KanjiVG path: ${path}`)
  }

  let current = { x: values[0], y: values[1] }
  const points = [{ x: round(current.x), y: round(current.y) }]

  for (let index = 2; index < values.length; index += 6) {
    const start = current
    const controlOne = { x: start.x + values[index], y: start.y + values[index + 1] }
    const controlTwo = { x: start.x + values[index + 2], y: start.y + values[index + 3] }
    const end = { x: start.x + values[index + 4], y: start.y + values[index + 5] }

    for (let sample = 1; sample <= samplesPerCurve; sample += 1) {
      const time = sample / samplesPerCurve
      const inverse = 1 - time
      points.push({
        x: round((inverse ** 3 * start.x) + (3 * inverse ** 2 * time * controlOne.x) + (3 * inverse * time ** 2 * controlTwo.x) + (time ** 3 * end.x)),
        y: round((inverse ** 3 * start.y) + (3 * inverse ** 2 * time * controlOne.y) + (3 * inverse * time ** 2 * controlTwo.y) + (time ** 3 * end.y)),
      })
    }

    current = end
  }

  return points
}

function singleCharacterEntries(script) {
  const characterIndex = script === 'hiragana' ? 1 : 2

  return kanaCatalog.flatMap((group) => group.entries
    .filter((entry) => [...entry[characterIndex]].length === 1)
    .map((entry) => ({
      id: entry[0],
      script,
      groupId: group.id,
      character: entry[characterIndex],
      romaji: entry[3],
    })))
}

async function fetchEntry(entry) {
  const sourceFile = codepointFile(entry.character)
  const response = await fetch(`${SOURCE_BASE}/${sourceFile}`)

  if (!response.ok) {
    throw new Error(`KanjiVG ${sourceFile} returned ${response.status}`)
  }

  const svg = await response.text()
  const strokes = extractStrokes(svg)
  if (!strokes.length) throw new Error(`No strokes found for ${entry.character}`)

  return {
    ...entry,
    sourceFile,
    strokes,
    referencePoints: strokes.map((stroke) => sampleStroke(stroke)),
    numbers: extractNumbers(svg),
  }
}

const entries = [
  ...singleCharacterEntries('hiragana'),
  ...singleCharacterEntries('katakana'),
]
const strokeEntries = await Promise.all(entries.map(fetchEntry))
const banner = `// Generated by scripts/generate-kana-strokes.mjs. Do not edit manually.
// Stroke data: KanjiVG, copyright Ulrich Apel, CC BY-SA 3.0.
// Source: https://github.com/KanjiVG/kanjivg/tree/${KANJIVG_COMMIT}

`

await mkdir(new URL('../src/data/writing/', import.meta.url), { recursive: true })
await writeFile(
  OUTPUT_FILE,
  `${banner}export const KANJIVG_COMMIT = '${KANJIVG_COMMIT}'\n\nexport const kanaStrokeCatalog = ${JSON.stringify(strokeEntries)}\n`,
)

console.log(`Generated ${strokeEntries.length} kana stroke entries in ${OUTPUT_FILE.pathname}`)
